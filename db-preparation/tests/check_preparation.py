from pathlib import Path
import json,re,unittest,os
R=Path(__file__).resolve().parents[1]
SOURCE=Path(os.environ.get('ISOLATED_SOURCE_ROOT',str(R.parent)))
D=json.loads((R/'source-metadata.json').read_text())
C=(R/'02_create_isolated_db_DRAFT.sql').read_text()
V=(R/'03_verify_isolated_db_READONLY.sql').read_text()
M=(R/'01_missing_metadata_readonly.sql').read_text()

# Lexical splitting only, NOT PostgreSQL syntax/runtime validation.
def statements(text):
 out=[];buf=[];i=0;state=None
 while i<len(text):
  if state:
   if state=='single':
    buf.append(text[i])
    if text[i]=="'":
     if i+1<len(text) and text[i+1]=="'":buf.append(text[i+1]);i+=1
     else:state=None
    i+=1;continue
   if text.startswith(state,i):buf.append(state);i+=len(state);state=None;continue
   buf.append(text[i]);i+=1;continue
  if text.startswith('--',i):
   j=text.find('\n',i);i=len(text) if j<0 else j+1;buf.append('\n');continue
  if text.startswith('/*',i):
   j=text.find('*/',i+2);assert j>=0;i=j+2;continue
  if text[i]=="'":state='single';buf.append(text[i]);i+=1;continue
  tag=re.match(r'\$[A-Za-z_0-9]*\$',text[i:])
  if tag:state=tag.group();buf.append(state);i+=len(state);continue
  if text[i]==';':
   if ''.join(buf).strip():out.append(''.join(buf).strip())
   buf=[];i+=1;continue
  buf.append(text[i]);i+=1
 assert state is None,'unterminated quote'
 assert not ''.join(buf).strip(),'unterminated statement'
 return out

class Checks(unittest.TestCase):
 def test_metadata_counts(self):self.assertEqual([len(D[k]) for k in ['①.csv','②.csv','③.csv','④.csv','➄.csv','⑥.csv']],[21,6,8,2,3,2])
 def test_exact_function_bodies_preserved(self):
  for f in D['➄.csv']:self.assertIn(f['definition'].replace('\r\n','\n').rstrip()+';',C)
 def test_identity_modes_not_uuid_guesses(self):
  self.assertIn('id bigint GENERATED BY DEFAULT AS IDENTITY (%s)',C);self.assertIn('id bigint GENERATED ALWAYS AS IDENTITY (%s)',C)
 def test_required_unresolved_inputs_block_creation(self):
  for x in ["approved_test_project_ref text := ''","sequence_settings jsonb := NULL","dependency_confirmed boolean := false","privileges_confirmed boolean := false","timezone_confirmed boolean := false"]:self.assertIn(x,C)
  self.assertLess(C.index('STOP: sequence/'),C.index('CREATE OR REPLACE FUNCTION'))
 def test_no_replacement_of_existing_tables_or_functions(self):
  self.assertIn("to_regclass('public.app_users')",C);self.assertIn("to_regprocedure('public.generate_application_code()')",C);self.assertIn('target is not empty',C)
 def test_indexes_preserved_not_deduplicated(self):
  for name in ['app_users_application_code_unique','app_users_line_user_id_unique','app_users_square_customer_id_unique']:self.assertIn('CREATE UNIQUE INDEX '+name,C)
  for c in D['②.csv']:self.assertIn('CONSTRAINT '+c['constraint_name'],C)
 def test_rls_no_policies(self):
  for t in ['app_users','app_backups']:self.assertIn('ALTER TABLE public.'+t+' ENABLE ROW LEVEL SECURITY;',C);self.assertIn('ALTER TABLE public.'+t+' NO FORCE ROW LEVEL SECURITY;',C)
  self.assertNotIn('CREATE POLICY',C)
 def test_column_compatibility_with_functions(self):
  tables={t:{r['column_name'] for r in D['①.csv'] if r['table_name']==t} for t in ['app_users','app_backups']}
  source=(SOURCE/'supabase/functions/line-trial-status/index.ts').read_text()
  columns=re.search(r'const columns\s*=\s*"([^"]+)"',source).group(1).split(',')
  self.assertTrue(set(columns)<=tables['app_users'])
  backup=(SOURCE/'supabase/functions/hosshii-backup/index.ts').read_text()
  for selection in re.findall(r"\.select\('([^']+)'\)",backup):
   self.assertTrue(set(selection.split(','))<=tables['app_users'] or set(selection.split(','))<=tables['app_backups'])
 def test_jsonb_and_conflict_target(self):
  self.assertIn('backup_data jsonb NOT NULL',C);self.assertIn('UNIQUE (line_user_id)',C);self.assertIn('DEFAULT generate_application_code()',C)
 def test_readonly_queries_select_only(self):
  for s in statements(M)+statements(V):self.assertRegex(s,r'^(SELECT|WITH)\b')
 def test_creation_lexical_structure_and_no_row_writes(self):
  stmts=statements(C);self.assertEqual(stmts[0],'BEGIN');self.assertEqual(stmts[-1],'COMMIT')
  self.assertNotRegex(C,r'(?i)\b(INSERT INTO|DELETE FROM|UPDATE public\.|DROP TABLE|CREATE EXTENSION)\b')
 def test_no_sensitive_literals(self):
  for f in D['➄.csv']:self.assertNotRegex(f['definition'],r'(?i)password|secret|token|https?://|service_role|sb_secret_|eyJ')
 def test_no_user_rows_or_current_sequence_counters(self):
  self.assertNotRegex(M+V,r'(?i)\bFROM\s+public\.(app_users|app_backups)\b')
  self.assertNotRegex(re.sub(r'--[^\n]*','',M+V),r'(?i)\blast_value\b|\bis_called\b')

if __name__=='__main__':unittest.main(verbosity=2)
