  r jsonb;
  settings jsonb := current_setting('hosshii.isolated.sequence_settings')::jsonb;
  options text;
  table_sql text;
BEGIN
  FOREACH t IN ARRAY ARRAY['app_users','app_backups'] LOOP
    SELECT e INTO STRICT r FROM jsonb_array_elements(settings) e WHERE e->>'table_name'=t;
    IF (r->>'sequence_type') IS DISTINCT FROM 'bigint' OR (r->>'sequence_schema') IS DISTINCT FROM 'public'
       OR (r->>'sequence_name') IS NULL OR r->>'sequence_name' !~ '^[a-z_][a-z0-9_]*$'
       OR (r->>'identity_kind') IS DISTINCT FROM (CASE WHEN t='app_users' THEN 'd' ELSE 'a' END)
       OR EXISTS (SELECT 1 FROM unnest(ARRAY['start_value','increment_by','min_value','max_value','cache_size']) k
                  WHERE (r->>k) IS NULL OR (r->>k) !~ '^-?[0-9]+$')
       OR r->>'cycle' NOT IN ('true','false') OR (r->>'cycle') IS NULL THEN
      RAISE EXCEPTION 'STOP: invalid/incomplete identity metadata for %',t;
    END IF;
    options := format('SEQUENCE NAME %I.%I START WITH %s INCREMENT BY %s MINVALUE %s MAXVALUE %s CACHE %s %s',
      r->>'sequence_schema',r->>'sequence_name',r->>'start_value',r->>'increment_by',
      r->>'min_value',r->>'max_value',r->>'cache_size',
      CASE WHEN (r->>'cycle')::boolean THEN 'CYCLE' ELSE 'NO CYCLE' END);
    table_sql := CASE t
      WHEN 'app_users' THEN format('CREATE TABLE public.app_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY (%s) NOT NULL,
