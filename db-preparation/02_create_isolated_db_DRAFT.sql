CREATE OR REPLACE FUNCTION public.prevent_trial_start_change()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
  IF OLD.trial_started_at IS NOT NULL
     AND NEW.trial_started_at IS DISTINCT FROM OLD.trial_started_at THEN
    RAISE EXCEPTION 'Trial start date cannot be changed';
  END IF;

  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.set_trial_end_date()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
BEGIN
  IF NEW.trial_started_at IS NOT NULL THEN
    NEW.trial_ends_at := NEW.trial_started_at + INTERVAL '21 days';
  END IF;

  RETURN NEW;
END;
$function$;

